test('module 4 verifies both Fibonacci orientations and internally consistent OHLC', () => {
  const [up, down] = editorial.assets.find(a => a.id === 'fibonacci-verificado').calculations;
  assert.equal(up.ascending, true);
  assert.equal(down.ascending, false);
  for (const example of [up, down]) {
    assert.deepEqual([example.low, example.high], [4, 9]);
    for (const { ratio, price } of example.levels) {
      const expected = example.ascending ? 4 + ratio * 5 : 9 - ratio * 5;
      assert.ok(Math.abs(price - expected) < 1e-6);
    }
  }
  assert.equal(up.levels.find(l => l.ratio === .382).price, 5.91);
  assert.equal(down.levels.find(l => l.ratio === .382).price, 7.09);
  const series = editorial.assets.find(a => a.id === 'tres-retrocesos').ohlc;
  assert.deepEqual(series.map(rows => rows.filter(r => r.close > r.open).length), [1, 2, 3]);
  for (const rows of series) for (const [i, row] of rows.entries()) {
    assert.ok(row.low <= Math.min(row.open, row.close));
    assert.ok(row.high >= Math.max(row.open, row.close));
    if (i) assert.equal(row.open, rows[i-1].close);
  }
});

